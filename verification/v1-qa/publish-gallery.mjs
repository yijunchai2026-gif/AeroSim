// Publish only genuine 100% native captures; no image editing, resizing, or acceptance claims.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const argv = process.argv.slice(2);
function option(name) {
  const index = argv.indexOf(name);
  return index < 0 ? undefined : argv[index + 1];
}
const captureArgument = option('--captures'), batch = option('--batch');
if (!captureArgument || !batch || !/^[a-z0-9][a-z0-9-]{2,64}$/.test(batch)) {
  throw new Error('Usage: node verification/v1-qa/publish-gallery.mjs --captures <native1920-dir> --batch candidate-20261008-01');
}
const captures = path.resolve(captureArgument);
const referenceFile = path.join(root, 'verification/v1-qa/reference-manifest.json');
const references = JSON.parse(fs.readFileSync(referenceFile, 'utf8'));
const nativeFile = path.join(captures, 'report.json');
if (!fs.existsSync(nativeFile)) throw new Error('Genuine native report.json is mandatory; curated PNGs alone cannot establish candidate provenance');
const native = JSON.parse(fs.readFileSync(nativeFile, 'utf8'));
if (!/^1\.0\./.test(native.version || '') || !native.startedUtc || native.width !== 1920 || native.height !== 1080) {
  throw new Error('Genuine 1.0 candidate version/UTC and real 1920x1080 viewport are mandatory; old 0.4 cannot be relabeled');
}
const sha = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
function dimensions(file) {
  const bytes = fs.readFileSync(file);
  if (!bytes.subarray(0, 8).equals(Buffer.from([137,80,78,71,13,10,26,10])) || bytes.length < 24) throw new Error('Not a genuine PNG: ' + file);
  return [bytes.readUInt32BE(16), bytes.readUInt32BE(20)];
}
const destination = path.join(root, 'assets/ui-v1', batch);
const reportHash = sha(nativeFile);
const oldManifest = path.join(destination, 'manifest.json');
if (fs.existsSync(oldManifest) && JSON.parse(fs.readFileSync(oldManifest, 'utf8')).sourceReportSha256 !== reportHash) {
  throw new Error('Candidate batch already contains another run; choose a fresh batch ID');
}
const images = references.screens.map(screen => {
  const sourceReference = path.join(root, screen.file);
  if (sha(sourceReference) !== screen.sha256) throw new Error('Locked reference changed: ' + screen.file);
  const matches = native.cases.filter(c => c.state === screen.state && Math.abs(c.scale - 1) < .001 && Math.abs(c.textMultiplier - 1) < .001 && c.screenshot);
  if (matches.length !== 1) throw new Error(`Expected exactly one 100% screenshot for ${screen.state}, found ${matches.length}`);
  const c = matches[0];
  if (c.width !== 1920 || c.height !== 1080 || path.basename(c.screenshot) !== c.screenshot || !c.screenshot.endsWith('.png')) throw new Error('Invalid capture metadata/path: ' + screen.state);
  const source = path.join(captures, c.screenshot);
  if (!fs.existsSync(source)) throw new Error('Incomplete 23-page native gallery; missing: ' + source);
  const [width, height] = dimensions(source);
  if (width !== 1920 || height !== 1080) throw new Error('Actual PNG size differs from baseline: ' + source);
  const target = path.join(destination, screen.state + '.png');
  const hash = sha(source);
  if (fs.existsSync(target) && sha(target) !== hash) throw new Error('Existing candidate PNG differs; choose a fresh batch ID: ' + target);
  return {id: screen.id, state: screen.state, reference: screen.file, referenceSha256: screen.sha256,
    actual: path.relative(root, target).split(path.sep).join('/'), actualSha256: hash,
    sourceScreenshot: c.screenshot, source, target,
    viewport: {width, height}, uiScale: 100, hudScale: 100, textScale: 100,
    semanticState: screen.semanticState, failedChecks: c.checks.filter(x => !x.passed).length,
    visualAcceptance: 'PENDING', userAcceptance: 'PENDING'};
});
if (images.length !== 23) throw new Error('Expected the complete locked 23-page design mapping');
const htmlFile = path.join(root, 'AeroSim-1.0-开发对照.html');
const marker = '<!-- Generated by verification/v1-qa/publish-gallery.mjs -->';
if (fs.existsSync(htmlFile) && !fs.readFileSync(htmlFile, 'utf8').startsWith(marker)) throw new Error('Refusing to overwrite a non-generated comparison document');
fs.mkdirSync(destination, {recursive: true});
for (const image of images) fs.copyFileSync(image.source, image.target);
const manifest = {schemaVersion: 1, batch, version: native.version, startedUtc: native.startedUtc,
  generatedUtc: new Date().toISOString(), viewport: {width: 1920, height: 1080}, uiScale: 100, hudScale: 100, textScale: 100,
  captureSource: 'Native Unity screenshot — isolated QA candidate and profile', sourceReportSha256: reportHash,
  sourceReportRelativePath: path.relative(root, nativeFile).split(path.sep).join('/'), referenceManifestSha256: sha(referenceFile),
  runtimeErrors: native.runtimeErrors, imageProcessing: 'Byte-identical PNG copy only; no resizing, painting, overlays, or masks',
  visualAcceptance: 'PENDING', userAcceptance: 'PENDING',
  limitations: ['Synthetic QA session data, not user achievements.', 'Concept artwork and native screenshots are distinctly labeled.',
    'No claim of pixel equality, complete features, mobile hardware validation, real online classrooms or FAA/Google Maps integration.'],
  screens: images.map(({source, target, ...image}) => image)};
fs.writeFileSync(oldManifest, JSON.stringify(manifest, null, 2) + '\n');
const esc = value => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
const figures = images.map(image => `<section id="page-${image.id}"><h2>${image.id} · ${esc(image.state)}</h2><p>${esc(image.semanticState)} · 当前截图 ${image.failedChecks} 条自动未通过/候选；视觉和人工验收 PENDING。</p><div class="pair"><figure><figcaption>原始概念图 · 1672×941 · 未修改</figcaption><a href="${esc(image.reference)}"><img loading="lazy" src="${esc(image.reference)}"></a></figure><figure><figcaption>${esc(native.version)} 开发候选 · 原始运行截图 · 1920×1080</figcaption><a href="${esc(image.actual)}"><img loading="lazy" src="${esc(image.actual)}"></a></figure></div></section>`).join('\n');
const index = images.map(image => `<a href="#page-${image.id}">${image.id} ${esc(image.state)}</a>`).join(' · ');
const html = `${marker}\n<!doctype html><html lang="zh-CN"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>AeroSim 1.0 开发候选 · 原图与实际对照</title><style>body{background:#090d14;color:#f2f6fc;font:16px/1.6 system-ui;margin:0}main{max-width:1840px;margin:auto;padding:28px}a{color:#8fb1ff}.notice{padding:18px;background:#2b2419;border-left:4px solid #ffb547}.pair{display:grid;grid-template-columns:1fr 1fr;gap:16px}figure{margin:0}img{width:100%;height:auto}figcaption{padding:8px 0}section{margin:36px 0;border-top:1px solid #2a374a;padding-top:12px}nav{font-size:14px}@media(max-width:960px){.pair{grid-template-columns:1fr}main{padding:16px}}</style><main><h1>AeroSim · 1.0 开发候选全页面对照</h1><p class="notice">应用版本 ${esc(native.version)} · 批次 ${esc(batch)} · 用户验收 PENDING。左图是23张原始概念效果图，右图是真正Unity运行截图；不把设计图冒充运行结果、不把版本号或几何通过冒充视觉一致。全部页面UI/HUD/Text100%，1920×1080。本机隔离QA数据不是用户成绩。</p><p>捕获UTC ${esc(native.startedUtc)} · Runtime errors ${esc(native.runtimeErrors)} · <a href="assets/ui-v1/${esc(batch)}/manifest.json">元数据与SHA256</a> · <a href="assets/ui-v1/${esc(batch)}/gallery.md">GitHub图文图册</a></p><nav>${index}</nav>${figures}<p>页面是否完整可用、视觉差异、缩放/键鼠/保存回归和真实设备需分别验收；本图册不证明iOS真机、多人课堂或实时空域服务已完成。</p></main></html>`;
fs.writeFileSync(htmlFile, html);
const markdown = '# AeroSim 1.0 开发候选真实截图图册\n\n' +
  `版本 ${native.version}；批次 ${batch}；捕获 ${native.startedUtc}；1920×1080，UI/HUD/Text100%。原图与运行截图分开显示；全部视觉/用户验收 PENDING，QA数据不是用户成绩。\n\n` +
  images.map(image => {
    const reference = path.relative(destination, path.join(root, image.reference)).split(path.sep).join('/');
    return `## ${image.id} · ${image.state}\n\n原始概念图：\n\n![原始设计 ${image.state}](${reference})\n\n${native.version} 原始运行截图：\n\n![实际候选 ${image.state}](${image.state}.png)\n\n`;
  }).join('') + '元数据与原图/截图哈希见 [manifest.json](manifest.json)。不代表视觉一致或用户验收。\n';
fs.writeFileSync(path.join(destination, 'gallery.md'), markdown);
console.log(JSON.stringify({pages: images.length, version: native.version, batch,
  manifest: oldManifest, html: htmlFile, imageProcessing: manifest.imageProcessing, userAcceptance: 'PENDING'}));
